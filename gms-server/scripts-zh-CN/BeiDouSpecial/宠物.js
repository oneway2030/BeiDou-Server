// 引用所需工具类（游戏脚本环境通常已全局提供）
const ItemInformationProvider = Java.type('org.gms.server.ItemInformationProvider');//导入 物品信息 类
const InventoryManipulator = Java.type('org.gms.client.inventory.manipulator.InventoryManipulator');
const Pet = Java.type('org.gms.client.inventory.Pet');
const I18nUtil = Java.type('org.gms.util.I18nUtil');

// 实现逻辑
function givePetToCharacter( itemId, quantity, time) {
    // 确保天数至少为1
    const days = Math.max(1, quantity);
    // 计算过期时间（当前时间 + 天数对应的毫秒数）
    const expiration = Date.now() + (time * 60 * 1000); // 1天 = 86400000毫秒
    // 创建宠物ID
    const petId = Pet.createPet(itemId);
    var chr = cm.getPlayer();
    // 向玩家添加宠物物品
    InventoryManipulator.addById(
        chr.getClient(),
        itemId,
        quantity,
        null,
        petId,
        expiration
    );
    var name = ItemInformationProvider.getInstance().getName(itemId);
    let tip = `恭喜你成功购买了90天： ${name}`;
    // 向玩家发送消息
    chr.message(tip);
}