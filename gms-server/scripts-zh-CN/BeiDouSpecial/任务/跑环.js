function levelStart() {
    var progress = parseInt(cm.getCharacterExtendValue(KEY_PROGRESS)) || 0;
    var taskIndexStr = cm.getCharacterExtendValue(KEY_TASK);
    var historyRings = parseInt(cm.getCharacterExtendValue(KEY_HISTORY)) || 0;
    var todayCompletedRings = parseInt(cm.getCharacterExtendValue(KEY_DAILY_RINGS, true)) || 0; // 每日重置

    var currentRound = progress % ROUNDS_PER_RING;
    var hasTask = taskIndexStr != null && taskIndexStr !== "" && taskIndexStr !== "null";

    var text = "\r\n                       #i03994060# #i03994063# #i03994067# #i03994062# #i03994073# #i03994079#\r\n\r\n";
    text += `#b================#b#e第${todayCompletedRings + 1}环#k  #r第${currentRound}/${ROUNDS_PER_RING}轮#b================#k#n\r\n\r\n`;
    text += `< 每日限制 >  #b${todayCompletedRings}/${MAX_DAILY_RINGS}环#k\r\n`;
    text += `< 累计环数 >  #r${historyRings}环#k\r\n`;

    if (todayCompletedRings >= MAX_DAILY_RINGS) {
        text += "\r\n#r今日跑环已完成，明天再来吧！#k";
        cm.sendOk(text);
        cm.dispose();
        return;
    }

    if (hasTask) {
        var taskIndex = parseInt(taskIndexStr);
        var task = TASK_LIST[taskIndex];


        text += "\r\n#e#k|------------------------------< 当前任务 >-------------------------------|#n#k\r\n\r\n";
        for (var i = 0; i < task[2].length; i++) {
            var id = task[2][i][0];
            var name = ItemInformationProvider.getInstance().getName(id);
            if (name == null || name === "") {
                text += `  #t${id}# #k#t${id}##k (ID：${id}) #kx${task[2][i][1]}\r\n`;
                text += `  #r(该任务道具有问题,请联系GM删除,并且自行跳过这论任务)#k\r\n`;
            } else {
                text += `  #v${id}# #k#t${id}##k (ID：${id}) #kx${task[2][i][1]}\r\n`;
            }
        }

        text += "\r\n#e#b|------------------------------< 奖励预告 >-------------------------------|#n#k\r\n\r\n";
        for (var i = 0; i < task[3].length; i++) {
            text += `  #v${task[3][i][0]}# #bx${task[3][i][1]}\r\n\r\n`;
        }
        text += `  #b金币：+3,000,000#k\r\n`;
        text += `  #b经验：当前等级经验的10%#k\r\n`;

        var bonus = getLevelBonus();
        text += "\r\n#e#r|----------------------------< 满轮奖励预告 >-------------------------|#n#k\r\n\r\n";
        for (var i = 0; i < bonus.items.length; i++) {
            text += `  #v${bonus.items[i][0]}# #r#t${bonus.items[i][0]}# x${bonus.items[i][1]}#k\r\n\r\n`;
        }
        if (bonus.meso > 0) {
            text += `  #r金币：+${bonus.meso}#k\r\n\r\n`;
        }
        if (bonus.nx > 0) {
            text += `  #r点卷：+${bonus.nx}#k\r\n\r\n`;
        }
        if (bonus.luckId > 0) {
            text += `  #r20%概率获得：#v${bonus.luckId}# #t${bonus.luckId}# x${bonus.luckCnt}#k\r\n`;
        }

        text += "\r\n#r#L0#【提交任务】#l#k#n";
        text += "        #k#L1#【放弃任务】#l#k#n";
        text += "\r\n#k#L2#【跳过一轮】#l#k#n";
        // 有配置传送地图才显示按钮
        if (task.length >= 7 && task[6]) {
            text += "        #k#L3#【快捷传送】#l#k#n\r\n";
        }
    } else {
        text += "\r\n#b#L0#【接取任务】#l#k#n\r\n";
    }
    cm.sendNextSelectLevel("HandleMenu", text);
}

function levelHandleMenu(selection) {
    var taskIndexStr = cm.getCharacterExtendValue(KEY_TASK);
    var hasTask = taskIndexStr != null && taskIndexStr !== "" && taskIndexStr !== "null";
    if (hasTask) {
        if (selection == 0) levelSubmitTask();
        if (selection == 1) levelAbandonTask();
        if (selection == 2) levelSkipRound(); // 跳过一轮
        if (selection == 3) levelWarpMonsterMap(); // 传送怪物地图
    } else {
        if (selection == 0) levelAcceptTask();
    }
}

// 传送怪物地图
function levelWarpMonsterMap() {
    // 检查金币
    if (cm.getPlayer().getMeso() < WARP_MONSTER_MAP_COST) {
        cm.sendOkLevel("Start", `#r金币不足！#k\r\n\r\n传送怪物地图需要消耗 #e${WARP_MONSTER_MAP_COST}万金币#k，你的金币不够！`);
        return;
    }

    var taskIndexStr = cm.getCharacterExtendValue(KEY_TASK);
    var taskIndex = parseInt(taskIndexStr);
    var task = TASK_LIST[taskIndex];

    if (!task || !(task.length >= 7 && task[6])) {
        cm.sendOkLevel("Start", "#r当前任务未配置传送地图！#k");
        return;
    }

    // 确认窗口
    var text = "#e#r【确认传送至怪物地图？】#n#k\r\n\r\n";
    text += `消耗：#e${WARP_MONSTER_MAP_COST}金币#k\r`;
    text += "传送后可快速击杀任务怪物收集物品\r\n\r\n";
    cm.sendYesNoLevel("Start", "ConfirmWarpMap", text);
}

// 确认传送
function levelConfirmWarpMap() {
    // 扣除金币
    cm.gainMeso(-WARP_MONSTER_MAP_COST);

    var taskIndexStr = cm.getCharacterExtendValue(KEY_TASK);
    var taskIndex = parseInt(taskIndexStr);
    var task = TASK_LIST[taskIndex];
    var mapId = task[6];

    // 传送
    cm.warp(parseInt(mapId));
    cm.sendOkLevel("Start", "#e【传送成功】#k\r\n\r\n已扣除500万金币，祝你任务顺利！");
}

