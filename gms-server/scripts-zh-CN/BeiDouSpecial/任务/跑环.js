// 获取等级奖励
function getLevelBonus() {
    var level = cm.getPlayer().getLevel();
    for (var i = 0; i < RING_BONUS_BY_LEVEL.length; i++) {
        var row = RING_BONUS_BY_LEVEL[i];
        var min = row[0], max = row[1];
        if (level >= min && level <= max) {
            return {
                items: row[2],
                meso: row[3],
                nx: row[4],
                luckId: row[5],
                luckCnt: row[6]
            };
        }
    }
    return {items: [], meso: 0, nx: 0, luckId: 0, luckCnt: 1};
}

