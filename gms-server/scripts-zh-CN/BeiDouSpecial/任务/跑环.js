function levelConfirmSkip() {
    // 扣除金币
    cm.gainMeso(-SKIP_ROUND_COST);

    var progress = parseInt(cm.getCharacterExtendValue(KEY_PROGRESS)) || 0;
    progress += 1; // 轮数+1

    // 清空当前任务、保存进度
    cm.saveOrUpdateCharacterExtendValue(KEY_TASK, "");
    cm.saveOrUpdateCharacterExtendValue(KEY_PROGRESS, progress + "");

    cm.sendOkLevel("Start", "#e【跳过成功】#k\r\n\r\n已消耗1亿金币，直接完成当前轮次！\r\n进度已更新，可接取下一轮任务～");
}

function levelAcceptTask() {
    var todayCompletedRings = parseInt(cm.getCharacterExtendValue(KEY_DAILY_RINGS, true)) || 0;
    if (todayCompletedRings >= MAX_DAILY_RINGS) {
        cm.sendOk("#r今日跑环次数已用尽，明天再来吧！#k");
        cm.dispose();
        return;
    }

    var playerLevel = cm.getPlayer().getLevel();
    var availableTasks = [];
    for (var i = 0; i < TASK_LIST.length; i++) {
        var t = TASK_LIST[i];
        if (playerLevel >= t[0] && playerLevel <= t[1]) {
            availableTasks.push(i);
        }
    }
    if (availableTasks.length == 0) {
        cm.sendOk("没有适合你等级的任务。");
        cm.dispose();
        return;
    }
    var rndIdx = availableTasks[Math.floor(Math.random() * availableTasks.length)];
    cm.saveOrUpdateCharacterExtendValue(KEY_TASK, String(rndIdx)); // 永久
    var task = TASK_LIST[rndIdx];
    var text = "#e#b|------------------------------< 收集物品 >-------------------------------|#n#k\r\n\r\n";
    for (var i = 0; i < task[2].length; i++) {
        var id = task[2][i][0];
        var name = ItemInformationProvider.getInstance().getName(id);
        if (name == null || name === "") {
            text += `  #t${task[2][i][0]}# #b#t${task[2][i][0]}##k (ID：${task[2][i][0]}) #bx${task[2][i][1]}\r\n`;
            text += `  #r(该任务道具有问题,请联系GM删除,并且自行跳过这论任务)#k\r\n`;
        } else {
            text += `  #v${task[2][i][0]}# #b#t${task[2][i][0]}##k (ID：${task[2][i][0]}) #bx${task[2][i][1]}\r\n`;
        }
    }
    cm.sendOk(text);
    cm.dispose();
}

function levelSubmitTask() {
    var taskIndexStr = cm.getCharacterExtendValue(KEY_TASK);
    var task = TASK_LIST[parseInt(taskIndexStr)];

    // debug模式：跳过所有检查，直接发奖励
    if (DEBUG) {
        levelGiveReward();
        return;
    }

    var missing = "";
    for (var i = 0; i < task[2].length; i++) {
        var id = task[2][i][0], need = task[2][i][1];
        if (cm.getItemQuantity(id) < need) {
            var name = ItemInformationProvider.getInstance().getName(id);
            if (name == null || name === "") {
                missing += `  #t${id}# #b#t${id}##k (ID：${id}) 缺 #r${need - cm.getItemQuantity(id)}#k个\r\n`;
                text += `  #r(该任务道具有问题,请联系GM删除,并且自行跳过这论任务)#k\r\n`;
            } else {
                missing += `  #v${id}# #b#t${id}##k (ID：${id}) 缺 #r${need - cm.getItemQuantity(id)}#k个\r\n`;
            }
        }
    }
    if (missing !== "") {
        cm.sendOkLevel("Start", "#r#e【物品不足】#k\r\n\r\n" + missing);
        return;
    }

    // 收集所有待发放道具
    var itemIds = [];
    var itemNums = [];
    for (var i = 0; i < task[3].length; i++) {
        itemIds.push(task[3][i][0]);
        itemNums.push(task[3][i][1]);
    }

    var progress = parseInt(cm.getCharacterExtendValue(KEY_PROGRESS)) || 0;
    var isFinishRing = (progress + 1) % ROUNDS_PER_RING == 0;
    var bonus = getLevelBonus();

    if (isFinishRing) {
        for (var i = 0; i < bonus.items.length; i++) {
            itemIds.push(bonus.items[i][0]);
            itemNums.push(bonus.items[i][1]);
        }
        if (bonus.luckId > 0) {
            itemIds.push(bonus.luckId);
            itemNums.push(bonus.luckCnt);
        }
    }
    // 增加服务端批量空位检测（根据待发放道具检查背包空位）
    if (!cm.canHoldAll(itemIds, itemNums)) {
        cm.sendOkLevel("Start", "#r【背包空位不足】，#b无法领取全部奖励，请清理背包后再提交！#k");
        cm.dispose();
        return;
    }

    levelGiveReward();
}

function levelGiveReward() {
    var taskIndexStr = cm.getCharacterExtendValue(KEY_TASK);
    var task = TASK_LIST[parseInt(taskIndexStr)];
    var progress = parseInt(cm.getCharacterExtendValue(KEY_PROGRESS)) || 0;

    // debug模式下不扣除需求物品
    if (!DEBUG) {
        for (var i = 0; i < task[2].length; i++) {
            cm.gainItem(task[2][i][0], -task[2][i][1]);
        }
    }

    var rewardText = "#e#k|------------------------------< 获得奖励 >-------------------------------|#n#k\r\n\r\n";
    for (var i = 0; i < task[3].length; i++) {
        cm.gainItem(task[3][i][0], task[3][i][1]);
        rewardText += `  #v${task[3][i][0]}# x${task[3][i][1]}\r\n\r\n`;
    }
    // 固定金币：每轮300W
    var fixedMeso = 5000000;
    cm.gainMeso(fixedMeso);
    rewardText += `  #k金币：+${fixedMeso}#k\r\n`;

    // 固定经验：当前等级升级所需经验的10%
    var expPercent = 0.1;
    var needExp = ExpTable.getExpNeededForLevel(cm.getPlayer().getLevel());
    var gainedExp = Math.floor(needExp * expPercent);
    cm.gainExp(gainedExp);
    rewardText += `  #k经验：+${gainedExp}#k\r\n`;

    progress++;
    cm.saveOrUpdateCharacterExtendValue(KEY_TASK, "");

    if (progress % ROUNDS_PER_RING == 0) {
        var historyRings = parseInt(cm.getCharacterExtendValue(KEY_HISTORY)) || 0;
        var todayCompletedRings = parseInt(cm.getCharacterExtendValue(KEY_DAILY_RINGS, true)) || 0;
        historyRings++;
        todayCompletedRings++;
        var bonus = getLevelBonus();

        var luckRate = 0.2;
        var roll = Math.random();
        var getLuck = (bonus.luckId > 0) && (roll <= luckRate);
        var canGetLuck = false;

        if (getLuck) {
            if (cm.canHold(bonus.luckId, bonus.luckCnt)) {
                canGetLuck = true;
                cm.gainItem(bonus.luckId, bonus.luckCnt);
            } else {
                cm.sendOk("背包空间不足，幸运奖励发放失败！请清理背包后重新提交任务！");
                cm.dispose();
                return;
            }
        }

        for (var i = 0; i < bonus.items.length; i++) {
            cm.gainItem(bonus.items[i][0], bonus.items[i][1]);
        }
        if (bonus.meso > 0) cm.gainMeso(bonus.meso);
        if (bonus.nx > 0) cm.getPlayer().getCashShop().gainCash(1, bonus.nx);

        // 满轮后重置进度为0，下一环从头开始
        progress = 0;

        // 保存
        cm.saveOrUpdateCharacterExtendValue(KEY_PROGRESS, progress + "");
        cm.saveOrUpdateCharacterExtendValue(KEY_HISTORY, historyRings + "");
        cm.saveOrUpdateCharacterExtendValue(KEY_DAILY_RINGS, todayCompletedRings + "", true); // 每日

        var text = `#e#r【恭喜完成第${historyRings}环】#n#k\r\n\r\n${rewardText}\r\n`;
        text += "#e#b|------------------------------< 额外奖励 >-------------------------------|#n#k\r\n\r\n";
        for (var i = 0; i < bonus.items.length; i++) {
            text += `  #v${bonus.items[i][0]}# #b#t${bonus.items[i][0]}# x${bonus.items[i][1]}#k\r\n\r\n`;
        }
        if (bonus.meso > 0) {
            text += `  #b金币：+${bonus.meso}#k\r\n\r\n`;
        }
        if (bonus.nx > 0) {
            text += `  #b点卷：+${bonus.nx}#k\r\n\r\n`;
        }
        if (getLuck && canGetLuck) {
            text += "#e#r|------------------------------< 幸运奖励 >-------------------------------|#n#k\r\n\r\n";
            text += `  #v${bonus.luckId}# #r#t${bonus.luckId}# x${bonus.luckCnt}（20%几率都被你拿到？狗托！）#r\r\n`;
        }

        if (todayCompletedRings >= MAX_DAILY_RINGS) {
            text += "\r\n#r今日跑环次数已用尽#k";
            cm.sendOk(text);
            cm.dispose();
        } else {
            cm.sendOkLevel("Start", text);
        }
    } else {
        cm.saveOrUpdateCharacterExtendValue(KEY_PROGRESS, progress + "");
        var text = `#r#e【恭喜完成第${progress}轮】#n#k\r\n\r\n${rewardText}`;
        cm.sendOkLevel("Start", text);
    }
}

function levelAbandonTask() {
    var progress = parseInt(cm.getCharacterExtendValue(KEY_PROGRESS)) || 0;
    if (progress < 0) progress = 0;
    var currentRound = progress % ROUNDS_PER_RING;
    if (currentRound === 0) {
        cm.sendOkLevel("Start", "当前处于 #r0 轮#k，不允许放弃任务！#k");
        return;
    }
    var text = "#r#e【确定放弃当前任务？】#n#k\r\n";
    text += `放弃任务将退回上一轮\r\n当前轮次：${currentRound} → ${currentRound > 0 ? currentRound - 1 : 0}`;
    cm.sendYesNoLevel("Start", "ConfirmAbandon", text);
}

function levelConfirmAbandon() {
    var progress = parseInt(cm.getCharacterExtendValue(KEY_PROGRESS)) || 0;

    if (progress > 0) {
        progress = progress - 1;
    } else {
        progress = 0;
    }

    cm.saveOrUpdateCharacterExtendValue(KEY_TASK, "");
    cm.saveOrUpdateCharacterExtendValue(KEY_PROGRESS, progress + "");

    cm.sendOkLevel("Start", "已放弃任务，进度#r#e【退回上一轮】#k#n");
}